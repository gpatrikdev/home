#!/usr/bin/env node
// Regenerates the agent files with Ruler, then rebuilds SKILLS.md.
// Run from the repo root:   node apply.mjs          (extra args go to Ruler)
// Rebuild the list only:    node apply.mjs --index-only
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const args = process.argv.slice(2);
const indexOnly = args.includes("--index-only");

if (!existsSync(join(root, ".ruler"))) {
  console.error("Run this from the repo root (no .ruler folder here).");
  process.exit(1);
}

if (!indexOnly) {
  const ruler = spawnSync("npx", ["@intellectronica/ruler", "apply", ...args], {
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (ruler.status !== 0) process.exit(ruler.status ?? 1);
}

// Domains: the root .ruler (shared) plus every top-level folder with its own .ruler.
const domains = [{ name: "shared", dir: join(root, ".ruler", "skills") }];
for (const entry of readdirSync(root, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
  const dir = join(root, entry.name, ".ruler", "skills");
  if (existsSync(dir)) domains.push({ name: entry.name, dir });
}

const sections = [];
let total = 0;
for (const domain of domains) {
  const rows = existsSync(domain.dir)
    ? readdirSync(domain.dir, { withFileTypes: true })
        .filter((e) => e.isDirectory() && existsSync(join(domain.dir, e.name, "SKILL.md")))
        .map((e) => skillRow(join(domain.dir, e.name), e.name))
        .sort((a, b) => a.name.localeCompare(b.name))
    : [];
  if (rows.length === 0) continue;
  total += rows.length;
  const where = domain.name === "shared" ? "`.ruler/skills/`" : `\`${domain.name}/.ruler/skills/\``;
  sections.push(
    [
      `## ${domain.name} (${rows.length})`,
      "",
      `Source folder: ${where}.`,
      "",
      "| Skill | Runs | What it does | Source |",
      "|---|---|---|---|",
      ...rows.map((r) => `| ${r.name} | ${r.runs} | ${cell(r.summary)} | ${r.source} |`),
    ].join("\n"),
  );
}

const out = [
  "# Skills",
  "",
  "<!-- Generated by apply.mjs. Do not edit; change .ruler folders and rerun it. -->",
  "",
  `${total} skills. "Automatically" means agents can load the skill on their own; ` +
    "you can also call those by name. The others run only when you type the command.",
  "",
  sections.join("\n\n"),
  "",
].join("\n");
writeFileSync(join(root, "SKILLS.md"), out);
console.log(`SKILLS.md: ${total} skills in ${sections.length} domain(s).`);

function skillRow(dir, folderName) {
  const meta = frontmatter(readFileSync(join(dir, "SKILL.md"), "utf8"));
  const name = meta.name || folderName;
  const typedOnly = String(meta["disable-model-invocation"]).toLowerCase() === "true";
  return {
    name,
    runs: typedOnly ? `\`/${name}\` only` : "automatically",
    summary: firstSentence(meta.description || ""),
    source: source(dir),
  };
}

// Minimal YAML frontmatter reader: `key: value`, quoted values, and > or | blocks.
function frontmatter(text) {
  const match = text.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const meta = {};
  const lines = match[1].split("\n");
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    if (/^[>|][-+]?$/.test(value)) {
      const block = [];
      while (i + 1 < lines.length && /^(\s+|$)/.test(lines[i + 1]) && lines[i + 1] !== "") {
        block.push(lines[++i].trim());
      }
      value = block.join(" ");
    } else if (/^(["']).*\1$/.test(value)) {
      value = value.slice(1, -1).replace(/\\"/g, '"');
    }
    meta[kv[1]] = value;
  }
  return meta;
}

function firstSentence(text) {
  const sentence = text.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? text;
  return sentence.length > 160 ? `${sentence.slice(0, 157)}...` : sentence;
}

function source(dir) {
  const file = join(dir, "SOURCE.txt");
  if (!existsSync(file)) return "local";
  const url = readFileSync(file, "utf8").match(/https:\/\/github\.com\/([^/\s]+\/[^/\s)]+)/);
  return url ? `[${url[1]}](https://github.com/${url[1]})` : "see SOURCE.txt";
}

function cell(text) {
  return text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}
